import { resolveGitCommit } from "./resolve-git-commit.mjs";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const commit = resolveGitCommit();
const commitShort = commit === "unknown" ? commit : commit.slice(0, 7);

const serverTs = `// Generated by scripts/write-build-info.mjs — do not edit
export const buildCommit = ${JSON.stringify(commit)};
export const buildCommitShort = ${JSON.stringify(commitShort)};
`;

writeFileSync(join(root, "server/src/config/build-info.ts"), serverTs);
